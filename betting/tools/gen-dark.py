#!/usr/bin/env python3
"""Generate dark-theme overrides for app.css.

Reads betting/app.css, finds every rule that paints a light surface, dark text
or a light border, and writes betting/dark.css with the same selectors under
html[data-theme="dark"] mapped to the dark palette. Rules that are already dark
(live block, match page, Me panel, headers, jackpot…) are skipped.

Run after changing app.css:   python3 betting/tools/gen-dark.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SRC, OUT = HERE / 'app.css', HERE / 'dark.css'

SURFACE = {  # light background -> dark background
    '#fff': '#1d2127', '#ffffff': '#1d2127', 'white': '#1d2127',
    '#fafafa': '#191c21', '#fafbfc': '#191c21', '#f8f8f9': '#15181c', '#f7f8fa': '#191c21', '#f6f7f9': '#22262d', '#f6f7f8': '#22262d',
    '#f3f4f6': '#262a31', '#f2f3f5': '#15181c', '#f1f2f4': '#262a31', '#f0f1f3': '#262a31', '#eef0f2': '#262a31', '#eceef1': '#121418',
    '#e9ebee': '#2a2f36', '#e8f4ec': '#183323', '#e3f3e8': '#183323', '#eef7f1': '#183323', '#e6f4ec': '#183323', '#e2f3e8': '#183323',
    '#fff8e1': '#3a3120', '#fffaf0': '#2e2a1f', '#fff4d1': '#3a3120', '#fffbea': '#3a3120', '#fff3cd': '#3a3120', '#fdecef': '#3a1f25', '#fde8ec': '#3a1f25', '#fde4e8': '#3a1f25', '#fff1d6': '#3a3120',
    '#dcdee3': '#2f343c', '#d6ebdc': '#2f343c', '#c8e3d0': '#3a4049', '#e5e8ec': '#3a4049', '#f1f3f5': '#2f343c',
}
TEXT = {  # dark text -> light text
    '#1c1f23': '#eef0f2', '#111': '#f4f5f6', '#111111': '#f4f5f6', '#1b1e25': '#eef0f2', '#222': '#eef0f2', '#000': '#fff',
    'var(--ink)': '#eef0f2', '#7a5a00': '#e8c56a', '#9a6400': '#f0b44a', '#b3112e': '#ff8a9b', '#1a7f37': '#4cd07d',
    '#3a3f45': '#c9cdd2', '#353a45': '#c9cdd2', '#4a4f57': '#b8bdc4', '#5d636b': '#a9aeb5', '#7d838c': '#9aa0a8',
}
BORDER = {
    '#e3e6ea': '#2c3138', '#e9ebee': '#2c3138', '#eef0f2': '#2c3138', '#f0f1f3': '#2c3138', '#e3e5e8': '#2c3138', '#e2e5e9': '#2c3138',
    '#f2f3f5': '#121418', '#e8eaed': '#2c3138', '#c3c7cd': '#3a4049',
    '#d3d7dc': '#3a4049', '#c9ccd1': '#3a4049', '#c9cdd2': '#3a4049', '#ccc': '#3a4049', '#eee': '#2c3138', '#e1e4e8': '#2c3138', '#c5e4cf': '#2a5a3a',
}
SKIP = re.compile(r'live-block|\.dots|\.dark\b|#page-match|me-dark|pg-dark|\.jp-|bd-top|wl-head|pg-head|\.topbar|#splash|\.sp-|\.toast|crash|\.game|games|v-head|md-hero|\.btn-gold|\.btn-accent|\.au-btn|\.lpill\.active|\.hot\b|\.badge|\.status|slip-pill|bottom-nav|\.ch-follow|\.ch-act|\.rs-lg|\.rs-date|\.el-live|\.au-bonus|\.wl-brand|\.wl-mm-logo|\.tx-st|\.bs-bar|\.bs-place|drawer-head|modal-logo|\.cat\b|\.tile|cc-top|desk-nav|\.pr-card|\.pr-cap|\.wl-tag|\.wl-demo b|\.age')
PROP = re.compile(r'(?<![-\w])(background(?:-color)?|color|border(?:-(?:top|bottom|left|right))?(?:-color)?|box-shadow)\s*:\s*([^;}]+)')


def mapval(prop, val):
    v = val.strip()
    low = v.lower()
    table = SURFACE if prop.startswith('background') else TEXT if prop == 'color' else BORDER
    out, changed = low, False
    for k in sorted(table, key=len, reverse=True):
        pat = re.compile(r'(?<![\w#])' + re.escape(k) + r'(?![0-9a-f])')
        if pat.search(out):
            out = pat.sub(table[k], out); changed = True
    return (out if changed else None)


def rules(css):
    """Yield (media, selector, body) for top-level and one-level-nested rules."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    def block(start):
        depth, j = 0, start
        while j < n:
            if css[j] == '{': depth += 1
            elif css[j] == '}':
                depth -= 1
                if depth == 0: return j
            j += 1
        return n
    while i < n:
        b = css.find('{', i)
        if b < 0: break
        head = css[i:b].strip()
        e = block(b)
        if head.startswith('@media') or head.startswith('@supports'):
            inner = css[b + 1:e]
            for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', inner):
                yield head, m.group(1).strip(), m.group(2)
        elif not head.startswith('@'):
            yield None, head, css[b + 1:e]
        i = e + 1


def main():
    out = ['/* GENERATED by tools/gen-dark.py from app.css – do not edit by hand. */',
           ':root[data-theme="dark"]{--bg:#121418;--line:#2c3138;--line-2:#3a4049;--text:#eef0f2;--muted:#9aa0a8;--odd:#2f343c;--odd-hover:#3a4049;--odd-ink:#36d26e;--g-bg:#2f343c;--ink-2:#c9cdd2;color-scheme:dark}',
           'html[data-theme="dark"],html[data-theme="dark"] body{background:#121418;color:#eef0f2}',
           'html[data-theme="dark"] input,html[data-theme="dark"] select,html[data-theme="dark"] textarea{background:#262a31;color:#eef0f2;border-color:#3a4049}',
           'html[data-theme="dark"] .odd{background:#2f343c;color:#36d26e}',
           'html[data-theme="dark"] .odd.sel{background:var(--brand);color:#fff}',
           'html[data-theme="dark"] .odd.locked{background:#262a31}',
           'html[data-theme="dark"] .au-btn.ghost{background:#1d2127}',
           'html[data-theme="dark"] .au-btn:disabled{background:#2f343c;color:#7d838c}',
           'html[data-theme="dark"] .au-tabs a:not(.on),html[data-theme="dark"] .au-row.links a{color:#4cd07d}']
    by_media = {}
    for media, sel, body in rules(SRC.read_text()):
        if SKIP.search(sel) or sel.startswith(':root') or sel.startswith('@'):
            continue
        decls = []
        for m in PROP.finditer(body):
            prop, val = m.group(1), m.group(2)
            if prop == 'box-shadow': continue
            nv = mapval(prop, val)
            if nv: decls.append(f'{prop}:{nv}')
        if not decls: continue
        sels = ','.join('html[data-theme="dark"] ' + s.strip() for s in sel.split(',') if s.strip() and not s.strip().startswith('html'))
        if not sels: continue
        by_media.setdefault(media, []).append(f'{sels}{{{";".join(decls)}}}')
    for media, lst in by_media.items():
        if media: out.append(media + '{\n' + '\n'.join(lst) + '\n}')
        else: out.extend(lst)
    OUT.write_text('\n'.join(out) + '\n')
    print(f'wrote {OUT.name}: {sum(len(v) for v in by_media.values())} rules')


if __name__ == '__main__':
    main()
